def source_map(cfg: dict) -> dict:
    """Extension -> language, the built-in table plus the config's extra_sources."""
    return {**SOURCE, **cfg.get("extra_sources", {})}


def family_of(path: str, cfg: dict):
    e = ext(path)
    return FAMILY.get(e) or (EXTRA if e in cfg.get("extra_sources", {}) else None)


def git(repo: str, *args: str) -> str:
    r = subprocess.run(["git", "-C", repo, "-c", "core.quotepath=off", *args], capture_output=True)
    if r.returncode != 0:
        raise RuntimeError(r.stderr.decode("utf-8", "replace").strip() or "git basarisiz")
    return r.stdout.decode("utf-8", "replace")


def has_git(repo: str) -> bool:
    """Git lists files here. Being inside some ancestor's work tree is not enough: a home directory
    under git with nothing tracked below `repo` would otherwise turn a real directory into an empty one."""
    try:
        return bool(git(repo, "ls-files").strip())
    except (RuntimeError, OSError):
        return False


def has_history(repo: str) -> bool:
    try:
        return has_git(repo) and bool(git(repo, "rev-parse", "--verify", "-q", "HEAD").strip())
    except (RuntimeError, OSError):
        return False


def build_dir(parts) -> bool:
    """A directory part that holds build output. `src/bin` is Rust source, not output."""
    return any(p in BUILD_DIRS and not (p == "bin" and i and parts[i - 1] == "src") for i, p in enumerate(parts))


def list_files(repo: str, pattern=None):
    """-> (paths, skipped_dirs{reason: [dirs]}). Git's tracked files; without git, a walk of the directory
    that does not enter build or hidden directories and reports each one it did not enter."""
    if has_git(repo):
        paths = git(repo, "ls-files").splitlines()
        skipped = {}
    else:
        paths, skipped = [], {}
        base = LONG_PREFIX + os.path.abspath(repo) if os.name == "nt" else repo   # os.walk skips long dirs silently
        for root, dirs, names in os.walk(base):
            rel = os.path.relpath(root, base).replace("\\", "/")
            rel = "" if rel == "." else rel + "/"
            keep = []
            for d in sorted(dirs):
                why = "gizli dizin" if d.startswith(".") else "derleme dizini" if build_dir((rel + d).split("/")) else None
                if why:
                    skipped.setdefault(why + " (girilmedi; git yok)", []).append(rel + d + "/")
                else:
                    keep.append(d)
            dirs[:] = keep
            paths += [rel + n for n in sorted(names)]
    if pattern:
        paths = [p for p in paths if glob_to_regex(pattern).match(p)]
    return paths, skipped


def cycles(edges) -> list:
    """Strongly connected groups of more than one module (Tarjan, iterative)."""
    graph = defaultdict(set)
    for a, b in edges:
        graph[a].add(b); graph.setdefault(b, set())
    index, low, on, stack, out, n = {}, {}, set(), [], [], [0]
    for root in list(graph):
        if root in index:
            continue
        work = [(root, iter(graph[root]))]
        index[root] = low[root] = n[0]; n[0] += 1; stack.append(root); on.add(root)
        while work:
            v, it = work[-1]
            for w in it:
                if w not in index:
                    index[w] = low[w] = n[0]; n[0] += 1; stack.append(w); on.add(w)
                    work.append((w, iter(graph[w]))); break
                if w in on:
                    low[v] = min(low[v], index[w])
            else:
                work.pop()
                if work:
                    low[work[-1][0]] = min(low[work[-1][0]], low[v])
                if low[v] == index[v]:
                    group = []
                    while True:
                        w = stack.pop(); on.discard(w); group.append(w)
                        if w == v:
                            break
                    if len(group) > 1:
                        out.append(sorted(group))
    return sorted(out)


def ext(path: str) -> str:
    return os.path.splitext(path)[1].lower()


def is_test(path: str) -> bool:
    return bool(TEST_HINT.search(path.replace("\\", "/")))


def glob_to_regex(pattern: str) -> "re.Pattern[str]":
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?"); i += 3
        elif pattern.startswith("**", i):
            out.append(".*"); i += 2
        elif pattern[i] == "*":
            out.append("[^/]*"); i += 1
        elif pattern[i] == "?":
            out.append("[^/]"); i += 1
        else:
            out.append(re.escape(pattern[i])); i += 1
    return re.compile("^" + "".join(out) + "$")


RUST_BIN = re.compile(r"(^|/)src/(main\.rs$|bin/)")


def entry_match(path: str, fam: str, name: str, wanted):
    """-> (source, config item) or None. `main` is a pattern: C anywhere, Rust only in a binary target (src/main.rs,
    src/bin/). Any other name only from the config: `name` anywhere, `glob:name` only in files the glob matches.
    A `main` in a library (a client's helper) is not an entry; to have one, name its path."""
    for w in wanted:
        g, _, n = w.rpartition(":")
        if n == name and (not g and name != "main" or g and glob_to_regex(g).match(path)):
            return "config", w
    if name == "main" and (fam == "c" or fam == "rs" and RUST_BIN.search(path)):
        return "main", None
    return None


def entry_order(x) -> tuple:
    """Binaries first: a long list is cut, and the real entry must not fall off the end alphabetically."""
    return (x["source"] != "main", not RUST_BIN.search(x["path"]), x["path"], x["line"])


def matches(path: str, globs) -> bool:
    return any(glob_to_regex(g).match(path.replace("\\", "/")) for g in (globs or []))


def load_config(repo: str, path):
    """-> (cfg, sources{key: 'config'|'varsayilan'}, errors[]). Unknown or malformed keys are errors."""
    cfg, sources, errors = dict(DEFAULTS), dict.fromkeys(DEFAULTS, "varsayilan"), []
    candidate = path or os.path.join(repo, "rontgen.config.json")
    if not os.path.exists(candidate):
        if path:
            errors.append(f"config bulunamadi: {path}")
        return cfg, sources, errors
    try:
        with io.open(candidate, encoding="utf-8") as f:
            raw = json.load(f)
    except (OSError, ValueError) as e:
        return cfg, sources, [f"config okunamadi: {e}"]
    if not isinstance(raw, dict):
        return cfg, sources, ["config bir nesne degil"]
    for key, value in raw.items():
        if key.startswith("_"):
            continue
        if key not in DEFAULTS:
            errors.append(f"bilinmeyen config anahtari: {key}")
        elif key == "report_lang":       # two runs stopped on "not a list": a valid value fell through to the list check
            if value in ("tr-ascii", "tr", "en"):
                cfg[key], sources[key] = value, "config"
            else:
                errors.append(f"report_lang bilinmiyor: {value!r} (tr-ascii, tr, en; varsayilana dusulmez)")
        elif key in INT_KEYS and (isinstance(value, bool) or not isinstance(value, int) or value <= 0):
            errors.append(f"{key} pozitif tamsayi degil: {value!r}")
        elif key == "extra_sources":
            bad = ([] if isinstance(value, dict) else ["nesne degil"]) or \
                  [f"{k!r}" for k, v in value.items() if not (isinstance(k, str) and re.fullmatch(r"\.[A-Za-z0-9_]+", k)
                                                               and (isinstance(v, str) and v.strip() or isinstance(v, dict)))]
            bad += [f"{k!r}: {e}" for k, v in (value.items() if not bad else []) if isinstance(v, dict) for e in ozel_dil.validate(v)]
            known = [k for k in value if k.lower() in SOURCE] if not bad else []
            if bad:
                errors.append(f"extra_sources gecersiz ('.uzanti': 'Dil adi' bekleniyor): {', '.join(bad)}")
            elif known:
                errors.append(f"extra_sources zaten kaynak olan uzantiyi yeniden tanimliyor: {', '.join(known)}")
            else:
                cfg[key], sources[key] = {k.lower(): v["name"] if isinstance(v, dict) else v for k, v in value.items()}, "config"
                cfg["_diller"] = {k.lower(): v for k, v in value.items() if isinstance(v, dict)}   # described languages
        elif key not in INT_KEYS and not (isinstance(value, list) and all(isinstance(x, str) for x in value)):
            errors.append(f"{key} metin listesi degil")
        else:
            cfg[key], sources[key] = value, "config"
    cfg["_dir"] = os.path.dirname(os.path.abspath(candidate))     # probe_results are looked up here first
    return cfg, sources, errors


def exclusion(path: str, text, cfg: dict):
    """Why a tracked source file is NOT measured, or None. Order: the stated decision first."""
    if matches(path, cfg["exclude_globs"]):
        return "config"
    parts = path.split("/")
    if build_dir(parts[:-1]):
        return "derleme dizini"
    name = parts[-1]
    if ".min." in name or HASHED.search(name):
        return "paketlenmis dosya adi"
    if GENERATED_NAME.search(name):
        return "uretilmis dosya adi"
    if text is not None:
        if GENERATED_MARK.search(text[:800]):
            return "uretilmis (dosya basinda isaret)"
        if "/Migrations/" in "/" + path and "MigrationBuilder" in text:
            return "uretilmis (veritabani gocu)"
        lines = text.splitlines()
        if lines and (max(len(x) for x in lines) > 5000 or len(text) / len(lines) > 300):
            return "uretilmis gorunuyor (cok uzun satirlar)"
    return None


def uzun_yol(path: str) -> str:
    """Windows: a path past MAX_PATH (260) opens only with the extended-length prefix; elsewhere unchanged.
    A Lean release with 244-character module paths lost 5,518 files to this."""
    if os.name != "nt" or len(path) < 240:
        return path
    full = os.path.abspath(path)
    return full if full.startswith(LONG_PREFIX) else LONG_PREFIX + full


LONG_PREFIX = "\\\\?\\"


def read_sources(repo: str, cfg: dict):
    """-> files{path: text}, excluded{reason: [paths]}, unclassified Counter(ext)."""
    files, unclassified = {}, Counter()
    paths, excluded = list_files(repo)
    for p in paths:
        if not p:
            continue
        e = ext(p)
        if e not in source_map(cfg):
            if e not in NOT_SOURCE:
                unclassified[e] += 1
            continue
        full = os.path.join(repo, p)
        try:
            if os.path.getsize(uzun_yol(full)) > MAX_BYTES:
                excluded.setdefault("2 MB'tan buyuk", []).append(p)
                continue
            with io.open(uzun_yol(full), encoding="utf-8", errors="replace") as f:
                text = f.read()
        except OSError:
            excluded.setdefault("okunamadi", []).append(p)
            continue
        why = exclusion(p, text, cfg)
        if why:
            excluded.setdefault(why, []).append(p)
        else:
            files[p] = text
    return files, excluded, unclassified


def thresholds_line(cfg: dict, sources: dict, keys) -> str:
    return "; ".join(f"{k} = {cfg[k]} ({sources[k]})" for k in keys)


def excluded_lines(excluded: dict) -> list:
    if not excluded:
        return ["- Dislanan kaynak dosyasi yok."]
    out = []
    for why, paths in sorted(excluded.items(), key=lambda x: -len(x[1])):
        shown = ", ".join(f"`{p}`" for p in sorted(paths)[:4]) + (" …" if len(paths) > 4 else "")
        unit = "dizin (icindeki dosyalar sayilmadi)" if all(p.endswith("/") for p in paths) else "dosya"
        out.append(f"- **{len(paths)} {unit}** — {why}: {shown}")
    return out


