"""Rontgen -- what the scripts share: which files count as source, which are
left out and why, and where every threshold comes from.

WHY THIS EXISTS
---------------
The first version measured build output as if someone had written it: a
bundled `index-DnlIJ73T.js` produced module edges and "mentioned" tables. And
its thresholds (600 lines, 160 columns) lived inside the code, where no
project could see or change them. Both are the same fault -- a decision made
silently on the reader's behalf.

So: every exclusion is reported with its reason, and every threshold is
printed with its source (`config` or `varsayilan`). A config key the scripts
do not know is an error, not something to ignore: a misspelt threshold that
is silently dropped measures with the default while the author believes
otherwise.

CONFIG (all keys optional) -- `rontgen.config.json` in the repository root,
or `--config <path>`:

    {
      "exclude_globs": ["**/wwwroot/uygulama/**"],
      "max_file_lines": 600,
      "max_line_length": 160,
      "max_commit_lines": 400,
      "module_depth": 3,
      "weak_edge": 2,
      "coverage_reports": ["coverage/coverage.cobertura.xml"],
      "probe_results": ["sondalar/di-kayitlari.json"],
      "extra_sources": {".spath": "S-Path"},
      "entry_points": ["kernel_main"]
    }

`entry_points` names functions that start the program where no `main` does
(a kernel entry, a plugin hook). Names are never guessed: a listed name that
is not found is reported as not found. `glob:name` limits a name to the
files the glob matches. `main` is a pattern, not a name (see entry_match).

`extra_sources` adds extensions the scripts do not know as source, with a
language name. They enter the inventory, the coverage ledger and the module
boxes, and may be the end of a probe edge; no edge, outline or blind spot is
extracted from them (the scripts cannot read the language). An extension that
is already source is an error, so a project cannot silently rename one.
"""
